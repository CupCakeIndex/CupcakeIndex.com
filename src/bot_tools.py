"""The site's Analyst chat (docs/bot.js) uses the same stat tools as Terry's Cupcake Analyst page (analyst/index.html),
so both answer from the same data the same way. This copies those tools out of the Analyst page into
docs/bot-tools.js, pointed at the site's own files, and copies the Analyst's data bundle to docs/data/analyst.json.

    python src/bot_tools.py        # after any change to the Analyst's tools (viz.yml also runs it every morning)

Never edit docs/bot-tools.js by hand: change analyst/index.html, then run this.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC, OUT = ROOT / "analyst" / "index.html", ROOT / "docs" / "bot-tools.js"
DATA_IN, DATA_OUT = ROOT / "analyst" / "data" / "rankings.json", ROOT / "docs" / "data" / "analyst.json"
START = "// ------------------------------------------------------------------ data (published with the page)"
END = "// ------------------------------------------------------------------ the prompt"


def swap(text, old, new, count=1):
    if text.count(old) != count:
        sys.exit(f"bot_tools.py: expected {count}x {old!r} in analyst/index.html, found {text.count(old)}. Update this script.")
    return text.replace(old, new)


def main():
    html = SRC.read_text(encoding="utf-8")
    body = html[html.index(START):html.index(END)]
    # the site serves every season from data/viz (team-only NFL seasons too) and the bundle as data/analyst.json
    body = swap(body, 'fetch("data/rankings.json")', 'fetch("data/analyst.json", { cache: "no-store" })')
    body = swap(body, 'fetch(`data/${dir}/${k}.json`)', 'fetch(`data/viz/${k}.json`)')
    # data/pace.json (the since-1999 pace history) isn't on the site: pace_to answers without that part
    body = re.sub(r"^const say = .*\n", "", body, count=1, flags=re.M)  # the chat shows progress its own way (setSay)
    js = f"""// GENERATED by src/bot_tools.py from analyst/index.html (the Cupcake Analyst's stat tools). Don't edit by hand:
// change the Analyst page, then run python src/bot_tools.py. The site's Analyst chat (bot.js) uses these.
const BotTools = (() => {{
  let say = () => {{}};
{body}
  return {{ TOOLS, base, load, seasons, teamSeasons, teamKey, norm, RATES, TEAM_RATES, setSay: (f) => {{ say = f; }}, data: () => R }};
}})();
"""
    OUT.write_text(js, encoding="utf-8", newline="\n")
    data = json.loads(DATA_IN.read_text(encoding="utf-8"))
    DATA_OUT.write_text(json.dumps(data, separators=(",", ":"), ensure_ascii=False), encoding="utf-8")
    print(f"{OUT.name}: {len(js) // 1024} KB, {DATA_OUT.name}: {DATA_OUT.stat().st_size // 1024} KB")


if __name__ == "__main__":
    main()
